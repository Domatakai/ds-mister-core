#!/usr/bin/env python3
"""The ratio bench's program, assembled by a real assembler.

tb/tb_cpu_clk.sv runs the *same* instruction sequence on the ARM9 and the ARM7
and compares how long each takes, so the sequence has to be encoded correctly
and has to be identical word for word: if the two programs differed by an
instruction, the comparison would be measuring the wrong thing. This script
assembles the routine with keystone, reads it back with capstone, and loads it
twice — once per core — with only the data-base literal differing (a literal
load, not a different instruction). Only the resulting hex is pasted into the
bench, so building the bench needs neither package; re-running this does:

    pip install keystone-engine capstone
    python tools/gen_clk_program.py --write

The routine: a 64-iteration register loop (so the run is long enough to
outlast the bus latency), then a store/load/store through main RAM, which is
what makes a missed bus response hang a gated core rather than go unnoticed.
"""
import sys

try:
    import capstone
    import keystone
except ImportError:  # pragma: no cover
    sys.exit("needs: pip install keystone-engine capstone")

KS = keystone.Ks(keystone.KS_ARCH_ARM, keystone.KS_MODE_ARM)
MD = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_ARM)

PROG9 = 0x02000000
PROG7 = 0x02000100
DATA9 = 0x02001000          # where each core writes its result
DATA7 = 0x02001100
LOOPS = 64
# sum of 1..64, then the same value read back and incremented: an ARM
# immediate cannot hold the data base, so the program loads it from a literal
# pool word instead — the same instruction in both copies, one different word.
RESULT = LOOPS * (LOOPS + 1) // 2

# The routine, with the two labels the branches need: keystone resolves them
# against the address the copy is assembled at, so both copies come out as the
# same bytes (a branch to a literal number would not: its displacement would
# move with the copy's base).
INSN = [
    "ldr r0, [pc, #0x28]",  # 0x00 the data-base literal at 0x30
    "mov r1, #0",           # 0x04 running sum
    "mov r2, #64",          # 0x08 loop counter
    "loop:",
    "add r1, r1, r2",       # 0x0C sum += counter
    "sub r2, r2, #1",       # 0x10
    "cmp r2, #0",           # 0x14
    "bne loop",             # 0x18
    "str r1, [r0]",         # 0x1C publish the sum through main RAM
    "ldr r3, [r0]",         # 0x20 read it back
    "add r3, r3, #1",       # 0x24
    "str r3, [r0, #4]",     # 0x28 and publish that
    "end:",
    "b end",                # 0x2C the marker the bench watches for
]
COUNT = len([i for i in INSN if not i.endswith(":")])
MARK_OFF = 4 * (COUNT - 1)
LIT_OFF = 4 * COUNT
STEPS = 6 + 4 * LOOPS + 4 + 1   # instructions executed to the marker


def encode(base, data):
    """Assemble the routine at `base` with `data` in its literal pool."""
    text = "\n".join(["start:"] + ["  " + i for i in INSN])
    code = KS.asm(text, base)[0]
    assert len(code) == 4 * COUNT, "assembler produced %d bytes" % len(code)
    words = [int.from_bytes(code[n:n + 4], "little") for n in range(0, len(code), 4)]
    words.append(data)                       # the literal pool word
    return words


def check(words, base):
    """Read the encoding back with an independent disassembler, and confirm
    that the marker really is the branch to itself at MARK_OFF."""
    code = b"".join(w.to_bytes(4, "little") for w in words[:-1])
    out = []
    for insn in MD.disasm(code, base):
        out.append("0x%02X  %-8s %s" % (insn.address - base, insn.mnemonic, insn.op_str))
    assert len(out) == COUNT, "capstone saw %d instructions" % len(out)
    # 0xEAFFFFFF is "B .": the branch offset that lands on the branch itself
    assert words[MARK_OFF // 4] == 0xEAFF_FFFE, \
        "the marker at 0x%02X (%08X) is not a branch to itself" \
        % (MARK_OFF, words[MARK_OFF // 4])
    return out


def fragments():
    p9 = encode(PROG9, DATA9)
    p7 = encode(PROG7, DATA7)
    # everything but the literal pool word must be identical
    assert p9[:-1] == p7[:-1], "the two copies differ by more than their literal"
    body = p9[:-1]
    dis = check(p9, PROG9)

    out = ["// Generated by tools/gen_clk_program.py — do not edit by hand.",
           "//",
           "// One ARM routine, loaded twice into main RAM with only its data-base",
           "// literal differing, so the ARM9 and the ARM7 run the same instruction",
           "// sequence and can be timed against each other.",
           "",
           "localparam [31:0] CLK_PROG9  = 32'h%08X;" % PROG9,
           "localparam [31:0] CLK_PROG7  = 32'h%08X;" % PROG7,
           "localparam [31:0] CLK_MARK9  = 32'h%08X;" % (PROG9 + MARK_OFF),
           "localparam [31:0] CLK_MARK7  = 32'h%08X;" % (PROG7 + MARK_OFF),
           "localparam [31:0] CLK_DATA9  = 32'h%08X;" % DATA9,
           "localparam [31:0] CLK_DATA7  = 32'h%08X;" % DATA7,
           "localparam [31:0] CLK_SUM    = 32'h%08X;   // %d loop steps" % (RESULT, LOOPS),
           "localparam [31:0] CLK_STEPS  = 32'd%d;     // instructions executed" % STEPS,
           ""]

    for name, base, lit in (("p9", PROG9, DATA9), ("p7", PROG7, DATA7)):
        out.append("task load_%s;" % name)
        out.append("\tbegin")
        for n, w in enumerate(body):
            out.append("\t\tram[16'h%04X] = 16'h%04X;   // %08X  %s"
                       % (((base - 0x02000000 + 4 * n) >> 1), w & 0xFFFF,
                          base + 4 * n, dis[n]))
            out.append("\t\tram[16'h%04X] = 16'h%04X;"
                       % (((base - 0x02000000 + 4 * n) >> 1) + 1, w >> 16))
        out.append("\t\tram[16'h%04X] = 16'h%04X;   // %08X  literal: data base"
                   % (((base - 0x02000000 + LIT_OFF) >> 1), lit & 0xFFFF, base + LIT_OFF))
        out.append("\t\tram[16'h%04X] = 16'h%04X;"
                   % (((base - 0x02000000 + LIT_OFF) >> 1) + 1, lit >> 16))
        for slot in (0, 1):
            idx = (DATA9 if name == "p9" else DATA7) - 0x02000000 + 4 * slot
            out.append("\t\tram[16'h%04X] = 16'h0000;" % (idx >> 1))
            out.append("\t\tram[16'h%04X] = 16'h0000;" % ((idx >> 1) + 1))
        out.append("\tend")
        out.append("endtask")
        out.append("")
    return "\n".join(out) + "\n"


def main():
    text = fragments()
    if len(sys.argv) > 1 and sys.argv[1] == "--write":
        with open("tb/tb_clk_prog.svh", "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote tb/tb_clk_prog.svh (%d lines)" % text.count("\n"))
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
