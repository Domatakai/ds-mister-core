#!/usr/bin/env python3
"""Generate rtl/bus/fw_default.sv - the DS firmware's two user-settings blocks.

The DS keeps its user settings in the wifi flash at 0x3FE00 and 0x3FF00, two
256-byte copies distinguished by an update counter, each protected by a
CRC16-CCITT. GBATEK's "DS Firmware User Settings" lists the layout; this script
writes that layout out with sane values (24-hour clock, an "NDS" nickname, and
a touchscreen calibration the core's TSC2046 model matches) so a game that
reads the settings finds a valid, self-consistent block.

The language field is the one setting the OSD drives: the base image is
English, and the RTL patches the language halfword (0x64) and the CRC that
covers it (0x72) from this script's per-language table, so the OSD "Language"
row reaches a game as the language the DS firmware would report. The table is
indexed by the OSD choice, not by GBATEK's code, so English (code 1) stays
index 0 and an unset .CFG stays English.

Run it from fpga/:  python tools/gen_fw_default.py
"""

NICKNAME = "NDS"
YEAR = 26             # 2026
# The OSD "Language" row, in menu order: (name, GBATEK language code).
# GBATEK: 0 Japanese, 1 English, 2 French, 3 German, 4 Italian, 5 Spanish.
LANGUAGES = [
    ("English",  1),
    ("Japanese", 0),
    ("French",   2),
    ("German",   3),
    ("Italian",  4),
    ("Spanish",  5),
]
# Touch calibration: ADC (x1,y1) at pixel (1,1), ADC (x2,y2) at pixel (254,190).
# nds_spi maps a stylus position to ADC as 0x100 + pixel*14, so these are the
# values that mapping produces at those pixels.
ADC1, SCR1 = 0x0100 + 1 * 14, 1
ADC2, SCR2 = 0x0100 + 254 * 14, 190


def crc16(data, crc=0xFFFF):
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            if crc & 0x8000:
                crc = ((crc << 1) ^ 0x1021) & 0xFFFF
            else:
                crc = (crc << 1) & 0xFFFF
    return crc


def block(update_counter, language):
    b = bytearray(b"\xff" * 256)
    b[0:0x74] = bytearray(0x74)                    # defined area starts zeroed
    b[0x00:0x02] = (5).to_bytes(2, "little")       # version, always 5
    b[0x02] = 0                                    # favourite colour: grey
    b[0x03] = 1                                    # birthday month
    b[0x04] = 1                                    # birthday day
    nick = NICKNAME.encode("utf-16-le")
    b[0x06:0x06 + len(nick)] = nick
    b[0x1A:0x1C] = len(NICKNAME).to_bytes(2, "little")
    b[0x52] = 0                                    # alarm hour
    b[0x53] = 0                                    # alarm minute
    b[0x58:0x5A] = ADC1.to_bytes(2, "little")      # touch adc (x1, y1)
    b[0x5A:0x5C] = ADC1.to_bytes(2, "little")
    b[0x5C] = SCR1                                 # touch screen (x1, y1)
    b[0x5D] = SCR1
    b[0x5E:0x60] = ADC2.to_bytes(2, "little")      # touch adc (x2, y2)
    b[0x60:0x62] = ADC2.to_bytes(2, "little")
    b[0x62] = SCR2 & 0xFF                          # touch screen (x2, y2)
    b[0x63] = SCR2 & 0xFF
    # the language code, with bits 10/11/13/14/15 set: settings valid, no
    # setup prompt
    b[0x64:0x66] = (0xEC00 | language).to_bytes(2, "little")
    b[0x66] = YEAR
    b[0x67] = 0x00
    b[0x68:0x6C] = (0).to_bytes(4, "little")       # RTC offset
    b[0x6C:0x70] = b"\xff" * 4
    b[0x70:0x72] = update_counter.to_bytes(2, "little")
    b[0x72:0x74] = crc16(b[0x00:0x70]).to_bytes(2, "little")
    b[0x74:0xFE] = b"\xff" * (0xFE - 0x74)         # no extended (iQue/DSi) data
    b[0xFE:0x100] = crc16(b[0x74:0xFE]).to_bytes(2, "little")
    return bytes(b)


HEADER = [
    "//============================================================================",
    "// NDS MiSTer Test - synthesised DS firmware user settings (generated)",
    "//",
    "// The two 256-byte user-settings blocks at 0x3FE00 and 0x3FF00, in the",
    "// layout GBATEK's *DS Firmware User Settings* documents, with valid",
    "// CRC16-CCITT protection. Generated by tools/gen_fw_default.py: edit that",
    "// script, not this file.",
    "//",
    "// English, 24-hour clock, nickname NDS, and a touch calibration matching the",
    "// core's TSC2046 model (ADC 0x0100 at pixel 1, 0x0F00 at pixel 254).",
    "//",
    "// `lang` is the OSD \"Language\" row: the base image is English and the",
    "// language halfword at 0x64 together with the CRC16 that covers it at 0x72",
    "// are substituted from the generated table below (both settings blocks",
    "// carry the same pair, since the CRC covers 0x00..0x6F, below the update",
    "// counter).",
    "//============================================================================",
    "module fw_default (",
    "\tinput      [8:0]  addr,",
    "\tinput      [2:0]  lang,   // 0 English, 1 Japanese, 2 French, 3 German,",
    "\t                          // 4 Italian, 5 Spanish",
    "\toutput     [7:0]  d",
    ");",
    "",
    "\t// 512 bytes, most significant byte first; the RTL selects one with +:",
    "\twire [4095:0] image = {",
]


def main():
    image = block(0, LANGUAGES[0][1]) + block(1, LANGUAGES[0][1])

    # per-language language halfword low byte and the CRC16-CCITT over
    # 0x00..0x6F, which is the halfword at 0x72
    codes, crcs = [], []
    for name, code in LANGUAGES:
        b = bytearray(block(0, code))
        codes.append(b[0x64])
        crcs.append(crc16(b[0x00:0x70]))
        assert b[0x65] == 0xEC, "the language halfword's high byte moved"
    # emit least-significant byte first: the RTL selects byte addr with
    # image[{addr,3'b000} +: 8]
    hexstr = "".join("%02x" % b for b in reversed(image))
    chunks = [hexstr[i:i + 128] for i in range(0, len(hexstr), 128)]
    lines = list(HEADER)
    for i, c in enumerate(chunks):
        sep = "," if i + 1 < len(chunks) else ""
        lines.append("\t\t512'h%s%s" % (c, sep))
    lines += [
        "\t};",
        "",
        "\t// The OSD language row, in menu order, and the CRC16-CCITT that",
        "\t// covers the block whenever the language halfword changes. Both",
        "\t// settings blocks share the pair: the CRC stops at 0x70, below the",
        "\t// update counter that differs between them.",
        "\tfunction [7:0] lang_byte(input [2:0] l);",
        "\t\tcase (l)",
    ]
    for i, (name, _) in enumerate(LANGUAGES):
        l = "\t\t3'd%d:" % i
        lines.append("%s lang_byte = 8'h%02X;%s" % (l, codes[i], "  // " + name))
    lines += [
        "\t\tdefault: lang_byte = 8'h%02X;" % codes[0],
        "\t\tendcase",
        "\tendfunction",
        "",
        "\tfunction [15:0] lang_crc(input [2:0] l);",
        "\t\tcase (l)",
    ]
    for i, (name, _) in enumerate(LANGUAGES):
        lines.append("\t\t3'd%d: lang_crc = 16'h%04X;%s" % (i, crcs[i], "  // " + name))
    lines += [
        "\t\tdefault: lang_crc = 16'h%04X;" % crcs[0],
        "\t\tendcase",
        "\tendfunction",
        "",
        "\twire [7:0]  off  = addr[7:0];",
        "\twire [7:0]  base = image[{addr, 3'b000} +: 8];",
        "\twire [15:0] crc  = lang_crc(lang);",
        "",
        "\tassign d = (off == 8'h64) ? lang_byte(lang) :",
        "\t           (off == 8'h65) ? 8'hEC :",
        "\t           (off == 8'h72) ? crc[7:0] :",
        "\t           (off == 8'h73) ? crc[15:8] : base;",
        "",
        "endmodule",
        "",
    ]
    with open("rtl/bus/fw_default.sv", "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote rtl/bus/fw_default.sv (%d bytes of settings)" % len(image))


if __name__ == "__main__":
    main()
