//============================================================================
// NDS MiSTer Test — 5x7 bitmap font
//
// Just enough alphabet for the boot menu: A-Z, 0-9 and a handful of
// punctuation, one 35-bit constant per glyph (7 rows of 5 bits, top row in
// the most significant bits). Anything unmapped renders as "?", so a ROM
// title full of accented or Japanese characters still shows something sane
// instead of a blank line.
//
//   row 0 = top scanline, bit 4 = leftmost column
//
// Codes: 0 space, 1..26 = A..Z, 27..36 = 0..9, then . - : / ? ( ) ,
//============================================================================
module font5x7 (
	input      [5:0] code,
	input      [2:0] row,
	output reg [4:0] bits
);

	reg [34:0] g;

	always @(*) begin
		case (code)
		6'd0:  g = 35'b00000_00000_00000_00000_00000_00000_00000;  // space
		6'd1:  g = 35'b01110_10001_10001_11111_10001_10001_10001;  // A
		6'd2:  g = 35'b11110_10001_10001_11110_10001_10001_11110;  // B
		6'd3:  g = 35'b01110_10001_10000_10000_10000_10001_01110;  // C
		6'd4:  g = 35'b11110_10001_10001_10001_10001_10001_11110;  // D
		6'd5:  g = 35'b11111_10000_10000_11110_10000_10000_11111;  // E
		6'd6:  g = 35'b11111_10000_10000_11110_10000_10000_10000;  // F
		6'd7:  g = 35'b01110_10001_10000_10111_10001_10001_01111;  // G
		6'd8:  g = 35'b10001_10001_10001_11111_10001_10001_10001;  // H
		6'd9:  g = 35'b01110_00100_00100_00100_00100_00100_01110;  // I
		6'd10: g = 35'b00111_00010_00010_00010_00010_10010_01100;  // J
		6'd11: g = 35'b10001_10010_10100_11000_10100_10010_10001;  // K
		6'd12: g = 35'b10000_10000_10000_10000_10000_10000_11111;  // L
		6'd13: g = 35'b10001_11011_10101_10101_10001_10001_10001;  // M
		6'd14: g = 35'b10001_11001_10101_10011_10001_10001_10001;  // N
		6'd15: g = 35'b01110_10001_10001_10001_10001_10001_01110;  // O
		6'd16: g = 35'b11110_10001_10001_11110_10000_10000_10000;  // P
		6'd17: g = 35'b01110_10001_10001_10001_10101_10010_01101;  // Q
		6'd18: g = 35'b11110_10001_10001_11110_10100_10010_10001;  // R
		6'd19: g = 35'b01111_10000_10000_01110_00001_00001_11110;  // S
		6'd20: g = 35'b11111_00100_00100_00100_00100_00100_00100;  // T
		6'd21: g = 35'b10001_10001_10001_10001_10001_10001_01110;  // U
		6'd22: g = 35'b10001_10001_10001_10001_10001_01010_00100;  // V
		6'd23: g = 35'b10001_10001_10001_10101_10101_11011_10001;  // W
		6'd24: g = 35'b10001_10001_01010_00100_01010_10001_10001;  // X
		6'd25: g = 35'b10001_10001_01010_00100_00100_00100_00100;  // Y
		6'd26: g = 35'b11111_00001_00010_00100_01000_10000_11111;  // Z
		6'd27: g = 35'b01110_10001_10011_10101_11001_10001_01110;  // 0
		6'd28: g = 35'b00100_01100_00100_00100_00100_00100_01110;  // 1
		6'd29: g = 35'b01110_10001_00001_00010_00100_01000_11111;  // 2
		6'd30: g = 35'b11111_00010_00100_00010_00001_10001_01110;  // 3
		6'd31: g = 35'b00010_00110_01010_10010_11111_00010_00010;  // 4
		6'd32: g = 35'b11111_10000_11110_00001_00001_10001_01110;  // 5
		6'd33: g = 35'b00110_01000_10000_11110_10001_10001_01110;  // 6
		6'd34: g = 35'b11111_00001_00010_00100_01000_01000_01000;  // 7
		6'd35: g = 35'b01110_10001_10001_01110_10001_10001_01110;  // 8
		6'd36: g = 35'b01110_10001_10001_01111_00001_00010_01100;  // 9
		6'd37: g = 35'b00000_00000_00000_00000_00000_01100_01100;  // .
		6'd38: g = 35'b00000_00000_00000_11111_00000_00000_00000;  // -
		6'd39: g = 35'b00000_01100_01100_00000_01100_01100_00000;  // :
		6'd40: g = 35'b00001_00010_00010_00100_01000_01000_10000;  // /
		6'd41: g = 35'b01110_10001_00001_00010_00100_00000_00100;  // ?
		6'd42: g = 35'b00010_00100_01000_01000_01000_00100_00010;  // (
		6'd43: g = 35'b01000_00100_00010_00010_00010_00100_01000;  // )

		default: g = 35'b00000_00000_00000_00000_00110_00110_01100; // ,
		endcase

		// row 0 is the top scanline, so it sits in the high bits
		bits = g[34 - 5 * row -: 5];
	end

endmodule
